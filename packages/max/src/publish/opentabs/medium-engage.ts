/**
 * Medium engagement — warmup via reading, clapping, and human-like responses.
 *
 * Anti-detection is the #1 priority. All defaults are conservative:
 *   - 4-7 articles opened per session, with realistic 45-120s "reading" dwell
 *   - 2-4 claps per session (clap button clicked 1-3 times with jitter)
 *   - 0-2 responses per session, hard-capped at 4/day
 *   - Long inter-article cooldowns (30-90s; 60-150s after a comment)
 *   - Randomised topic + random offset into the tag feed (don't always hit top 6)
 *   - Dedup via data/medium-engaged.json (never engage same URL twice)
 *   - Daily caps persisted on disk (restart-safe)
 *   - Fallback to waitForHuman on the response editor when selectors drift
 *
 * Response ("comment") copy is generated by Claude Haiku with strict constraints:
 *   - Must reference a specific claim or line from the article
 *   - 1-3 sentences, no em-dashes, no "Great insights", no "As an AI"
 *   - Conversational developer register
 *
 * Usage (via --mode medium-engage in index.ts):
 *   node dist/index.js --mode medium-engage
 *   node dist/index.js --mode medium-engage --dry-run
 *   node dist/index.js --mode medium-engage --topic artificial-intelligence
 */

