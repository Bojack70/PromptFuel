// ─── History helpers ────────────────────────────────────────────────────────

function loadHistory(dataDir: string): EngagementHistory {
  const file = join(dataDir, HISTORY_FILE);
  if (!existsSync(file)) return { entries: [] };
  try {
    return JSON.parse(readFileSync(file, 'utf-8')) as EngagementHistory;
  } catch {
    return { entries: [] };
  }
}

function saveHistory(dataDir: string, history: EngagementHistory): void {
  writeFileSync(join(dataDir, HISTORY_FILE), JSON.stringify(history, null, 2));
}

function todayUTC(): string {
  return new Date().toISOString().split('T')[0];
}

function countToday(history: EngagementHistory, action: EngagementEntry['action']): number {
  const d = todayUTC();
  return history.entries.filter((e) => e.date === d && e.action === action).length;
}

function isAlreadyEngaged(history: EngagementHistory, url: string): boolean {
  return history.entries.some((e) => normaliseUrl(e.url) === normaliseUrl(url));
}

function normaliseUrl(url: string): string {
  // Strip tracking params + trailing slash for stable dedup
  try {
    const u = new URL(url);
    return `${u.origin}${u.pathname.replace(/\/$/, '')}`;
  } catch {
    return url.replace(/[?#].*$/, '').replace(/\/$/, '');
  }
}

// ─── Topic selection ────────────────────────────────────────────────────────

function pickTopic(history: EngagementHistory, forced?: string): string {
  if (forced && TOPICS.includes(forced)) return forced;
  if (forced) return forced; // allow off-list topics if explicitly requested

  // Bias away from topics used in the last 3 sessions
  const recent = history.entries.slice(-15).map((e) => extractTopicHint(e.url)).filter(Boolean);
  const weights = TOPICS.map((t) => (recent.includes(t) ? 0.4 : 1.0));
  const total = weights.reduce((s, w) => s + w, 0);
  let r = Math.random() * total;
  for (let i = 0; i < TOPICS.length; i++) {
    r -= weights[i];
    if (r <= 0) return TOPICS[i];
  }
  return TOPICS[0];
}

